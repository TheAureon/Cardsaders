// Bundles the game into one self-contained index.html (JS + CSS inlined, classic
// script) so it plays by double-clicking the file, with no server or terminal.
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'es2020',
  outdir: 'out',
  write: false,
  legalComments: 'none',
});

const js = result.outputFiles.find((f) => f.path.endsWith('.js')).text.replace(/<\/script/gi, '<\\/script');
const css = result.outputFiles.find((f) => f.path.endsWith('.css'))?.text ?? '';

const template = readFileSync('dev.html', 'utf8');
const marker = /\s*<script type="module" src="\/src\/main.ts"><\/script>/;
if (!marker.test(template)) throw new Error('dev.html: main.ts script tag not found');
const html = template
  // Function replacers: the minified code contains `$&`-style sequences.
  .replace('</head>', () => `  <style>${css}</style>\n  </head>`)
  .replace(marker, () => `\n    <script>${js}</script>`)
  .replace('<head>', '<head>\n    <!-- Generated by scripts/build-standalone.mjs from dev.html. Do not edit by hand. -->');

writeFileSync('index.html', html);
mkdirSync('dist', { recursive: true });
writeFileSync('dist/index.html', html);
console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB (also copied to dist/index.html)`);
